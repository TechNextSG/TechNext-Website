def asset_version() -> str:
    """Short content hash of the CSS/JS bundle, appended as ?v= so a deploy never serves a cached stylesheet
    against new markup (GitHub Pages caches assets for ~10 minutes)."""
    import hashlib
    h = hashlib.sha1()
    for f in sorted((ROOT / "assets").glob("css/*.css")) + sorted((ROOT / "assets").glob("js/*.js")):
        h.update(f.read_bytes())
    return h.hexdigest()[:8]


def write_app_slugs():
    """assets/js/app-slugs.js: the app-page URL map for the scripts that link to app pages (hero pop-ups,
    the suite, the app map). Written before the asset hash so the ?v= covers it."""
    js = ('/* © TechNext Pte. Ltd. (technext.asia). All rights reserved. Generated by _src/build.py from sitedata.APP_SLUG. */\n'
          'window.TN_APP_SLUG = ' + json.dumps(S.APP_SLUG, sort_keys=True, separators=(',', ':')) + ';\n')
    p = ROOT / 'assets' / 'js' / 'app-slugs.js'
    if not p.exists() or p.read_text(encoding='utf-8') != js:
        p.write_text(js, encoding='utf-8', newline='\n')


